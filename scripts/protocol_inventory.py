"""Regenerate source-derived protocol inventories; no server execution or dependencies."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reference/upstream/Database/Laragon/ninjasage'
COMMIT = 'ecf9012d885d1c89fd5f42791eed4f37f90f2edd'


def location(path, line):
    rel = path.relative_to(SOURCE).as_posix()
    return f'[{rel}:{line}](../../reference/upstream/Database/Laragon/ninjasage/{rel}#L{line})'


def write(name, lines):
    target = ROOT / 'docs/inventory' / name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def amf():
    lines = ['# AMF method inventory', '', f'Reference: `{COMMIT}`. Source inspection only; no client or server execution.', '',
             'Generated by `python scripts/protocol_inventory.py`. Public method declarations are extracted from PHP source. Constructors are excluded. This is a declaration inventory, not an authorization allowlist: PHP reflection also sees nonpublic/inherited methods, and the upstream dispatcher does not enforce an explicit allowlist.', '',
             'Top-level `*Service.php` classes in `App\\Services\\Amf` resolve first; `App\\Services` is the fallback. Targets shown use the short service name; the `Service` suffix is also accepted. Nested helper namespaces cannot be addressed through ordinary `Service.method` names. Trait/inherited methods and dynamically constructed targets require separate review.', '']
    count = 0
    for title, paths in [('Gateway-resolvable declared methods', sorted((SOURCE / 'app/Services/Amf').glob('*Service.php')) + sorted((SOURCE / 'app/Services').glob('*Service.php'))),
                         ('Internal helpers and other declarations', sorted(p for p in (SOURCE / 'app/Services/Amf').rglob('*.php') if p.parent != SOURCE / 'app/Services/Amf' or not p.name.endswith('Service.php')))]:
        lines += [f'## {title}', '', '| Target / helper | Parameters | Source |', '|---|---|---|']
        section_count = 0
        for path in paths:
            source = path.read_text(encoding='utf-8-sig')
            for match in re.finditer(r'public\s+(?:static\s+)?function\s+([A-Za-z_][A-Za-z_0-9]*)\s*\((.*?)\)', source, re.S):
                method, params = match.groups()
                if method == '__construct':
                    continue
                line = source.count('\n', 0, match.start()) + 1
                params = ' '.join(params.split()).replace('|', '\\|')
                service = path.stem.removesuffix('Service') if title.startswith('Gateway') else path.relative_to(SOURCE / 'app/Services/Amf').with_suffix('').as_posix()
                lines.append(f'| `{service}.{method}` | `{params}` | {location(path, line)} |')
                section_count += 1
        lines += ['', f'{section_count} public declarations in this section.', '']
        count += section_count
    lines += [f'Total: {count} public declarations. See [AMF contract](../protocols/amf.md) for argument normalization and errors.']
    write('amf-methods.md', lines)


def sockets():
    lines = ['# Socket event inventory', '', f'Reference: `{COMMIT}`. Source-derived, not a captured wire trace.', '',
             'Generated by `python scripts/protocol_inventory.py`. Lists literal event names passed to `socket.on`, `.emit`, and the battle broadcast helpers. Lifecycle `disconnect` is included. Dynamic event names and comments are not treated as independent client events. Payload expressions are pointers to source, not full schemas.', '']
    for server in ['chat-server', 'pvp-server']:
        lock = json.loads((SOURCE / server / 'package-lock.json').read_text())
        versions = {k: lock['packages'][f'node_modules/{k}']['version'] for k in ['socket.io', 'engine.io', 'socket.io-parser', 'engine.io-parser']}
        lines += [f'## {server}', '', 'Locked dependencies: ' + ', '.join(f'`{k} {v}`' for k, v in versions.items()) + '.', '', '| Direction | Event | Source |', '|---|---|---|']
        rows = []
        for path in sorted((SOURCE / server).rglob('*.js')):
            if 'node_modules' in path.parts:
                continue
            source = path.read_text(encoding='utf-8-sig')
            for match in re.finditer(r"(?:\bsocket\.(on)|\.(emit)|\.(_broadcastAll|_broadcastParticipants|_broadcastSpectators))\(\s*['\"]([^'\"]+)['\"]", source):
                direction = 'Client → server' if match[1] else 'Server → client'
                line = source.count('\n', 0, match.start()) + 1
                rows.append((direction, match[4], path, line))
        for direction, event, path, line in sorted(rows, key=lambda x: (x[0], x[1], str(x[2]), x[3])):
            lines.append(f'| {direction} | `{event}` | {location(path, line)} |')
        lines += ['', f'{len(set((r[0], r[1]) for r in rows))} distinct direction/event pairs; repeated call sites retained.', '']
    lines += ['See [Socket.IO contract](../protocols/socket-io.md) and [Flash policy](../protocols/flash-policy.md).']
    write('socket-events.md', lines)


if __name__ == '__main__':
    if not SOURCE.is_dir():
        raise SystemExit('Pinned reference checkout is missing; see reference/README.md.')
    amf()
    sockets()
    print('Regenerated AMF methods and Socket.IO events.')
